"""Render the README progress card: an SVG with the overall coverage and one bar per module.

Used by tools/coverage.py, which writes one card per GitHub theme (docs/progress-light.svg,
docs/progress-dark.svg); the README picks one with <picture>. Pure standard library and
deterministic, so `coverage.py --check` can compare the output byte for byte.
"""

# Two columns of (section title, rows); a row is (label, modules) and shows their sum.
COLUMNS = [
    [("Toshi engine", [(m, [m]) for m in (
        "TKernelInterface", "TApplication", "TInputInterface", "TInputDXInterface", "TRenderInterface",
        "TRenderD3DInterface", "TTerrainInterface", "TGuiInterface")])],
    [("Game libraries", [(m, [m]) for m in ("PPropertyParser", "PGUICore", "PGUIRenderer", "SimJPTerrain", "Units")]),
     ("Shader plugins", [("Shaders/D3D (5 DLLs)", ["TLineShaderD3D", "TSkinShaderD3D", "TSpriteShaderD3D",
                                                    "TSysShaderD3D", "TTerrainShaderD3D"])]),
     ("Game", [("SimJP.exe", ["SimJP"])])],
]

# GitHub's light and dark palettes (Primer).
THEMES = {
    "light": {"bg": "#f6f8fa", "border": "#d1d9e0", "text": "#1f2328", "muted": "#59636e", "track": "#e1e6eb"},
    "dark": {"bg": "#151b23", "border": "#3d444d", "text": "#f0f6fc", "muted": "#9198a1", "track": "#2a313c"},
}
GREEN, AMBER = ("#1f883d", "#3fb950"), "#d29922"
FONT = "-apple-system,BlinkMacSystemFont,'Segoe UI','Noto Sans',Helvetica,Arial,sans-serif"
MONO = "ui-monospace,SFMono-Regular,'SF Mono',Menlo,Consolas,'Liberation Mono',monospace"

WIDTH, PAD, GAP = 880, 28, 40
ROW, SECTION = 38, 24


def render(stats, theme):
    """stats maps every module in COLUMNS to (reimplemented, counted) functions."""
    c = THEMES[theme]
    col_width = (WIDTH - 2 * PAD - GAP) // 2
    done = sum(i for i, _ in stats.values())
    total = sum(n for _, n in stats.values())
    complete = sum(1 for i, n in stats.values() if n and i == n)
    percent = 100.0 * done / total

    def bar(x, y, w, h, ratio, fill):
        track = f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{h / 2:g}" fill="{c["track"]}"/>'
        if ratio <= 0:
            return track
        return track + (f'<rect x="{x}" y="{y}" width="{max(w * ratio, h):.1f}" height="{h}" rx="{h / 2:g}" '
                        f'fill="{fill}"/>')

    body = [
        f'<text x="{PAD}" y="46" class="label">REIMPLEMENTATION PROGRESS</text>',
        f'<text x="{PAD}" y="100" class="big">{percent:.1f}%</text>',
        f'<text x="{WIDTH - PAD}" y="74" class="stat" text-anchor="end">{done:,} / {total:,}</text>',
        f'<text x="{WIDTH - PAD}" y="96" class="muted" text-anchor="end">'
        "original functions reimplemented</text>",
        f'<text x="{WIDTH - PAD}" y="116" class="muted" text-anchor="end">'
        f'{complete} of {len(stats)} modules complete</text>',
        bar(PAD, 134, WIDTH - 2 * PAD, 12, done / total, "url(#green)"),
    ]
    bottoms = []
    for column, sections in enumerate(COLUMNS):
        x, y = PAD + column * (col_width + GAP), 186
        for title, rows in sections:
            body.append(f'<text x="{x}" y="{y}" class="label">{title.upper()}</text>')
            y += SECTION
            for label, modules in rows:
                implemented = sum(stats[m][0] for m in modules)
                counted = sum(stats[m][1] for m in modules)
                full = implemented == counted
                check = '<tspan class="check" dx="6">✓</tspan>' if full else ""
                body.append(
                    f"<g><title>{label}: {implemented:,} of {counted:,} functions</title>"
                    f'<text x="{x}" y="{y + 4}" class="name">{label}{check}</text>'
                    f'<text x="{x + col_width}" y="{y + 4}" class="num" text-anchor="end">{implemented:,} / '
                    f'{counted:,}<tspan class="pct" dx="10">{implemented / counted:.0%}</tspan></text>'
                    f'{bar(x, y + 12, col_width, 6, implemented / counted, "url(#green)" if full else AMBER)}</g>')
                y += ROW
            y += 10
        bottoms.append(y)
    height = max(bottoms) - 10

    style = "".join([
        f".label{{font:600 11px {FONT};letter-spacing:1.4px;fill:{c['muted']}}}",
        f".big{{font:700 48px {FONT};fill:{c['text']}}}",
        f".stat{{font:600 20px {MONO};fill:{c['text']}}}",
        f".muted{{font:400 13px {FONT};fill:{c['muted']}}}",
        f".name{{font:500 13px {FONT};fill:{c['text']}}}",
        f".num{{font:400 11px {MONO};fill:{c['muted']}}}",
        f".pct{{font-weight:700;fill:{c['text']}}}",
        f".check{{font-weight:700;fill:{GREEN[1]}}}",
    ])
    return "\n".join([
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{height}" '
        f'viewBox="0 0 {WIDTH} {height}" role="img" aria-label="Reimplementation progress: {percent:.1f}%">',
        "<!-- Generated by tools/coverage.py; do not edit. -->",
        f"<style>{style}</style>",
        f'<defs><linearGradient id="green" x1="0" x2="1"><stop offset="0" stop-color="{GREEN[0]}"/>'
        f'<stop offset="1" stop-color="{GREEN[1]}"/></linearGradient></defs>',
        f'<rect x="0.5" y="0.5" width="{WIDTH - 1}" height="{height - 1}" rx="12" fill="{c["bg"]}" '
        f'stroke="{c["border"]}"/>',
        *body,
        "</svg>",
        "",
    ])
